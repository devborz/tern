import Foundation

/// Installs Tern's zsh integration scripts and describes how to load them.
///
/// zsh is started with `ZDOTDIR` pointing at a directory holding our own
/// `.zshenv`. That file restores the user's `ZDOTDIR`, sources the user's
/// `.zshenv`, and loads the integration script; zsh then reads `.zprofile`,
/// `.zshrc` and `.zlogin` from the user's directory as usual.
nonisolated enum ZshIntegration {
    struct Installation: Sendable {
        let zdotdir: URL
        let script: URL
    }

    /// Writes the scripts into Application Support. Rewritten on every launch
    /// so they always match the running app version.
    static let installation: Installation? = {
        let fileManager = FileManager.default
        guard let support = fileManager.urls(for: .applicationSupportDirectory, in: .userDomainMask).first else {
            return nil
        }
        let directory = support
            .appendingPathComponent(Bundle.main.bundleIdentifier ?? "Tern", isDirectory: true)
            .appendingPathComponent("ShellIntegration/zsh", isDirectory: true)
        let script = directory.appendingPathComponent("tern-integration.zsh")
        do {
            try fileManager.createDirectory(at: directory, withIntermediateDirectories: true)
            try bootstrapScript.write(to: directory.appendingPathComponent(".zshenv"), atomically: true, encoding: .utf8)
            try integrationScript.write(to: script, atomically: true, encoding: .utf8)
        } catch {
            NSLog("Tern: cannot install zsh integration: \(error)")
            return nil
        }
        return Installation(zdotdir: directory, script: script)
    }()

    /// zsh-autosuggestions 0.7.1 (MIT, license in the file header), shipped
    /// in the app bundle and sourced from there.
    static let autosuggestionsScript = Bundle.main.url(forResource: "zsh-autosuggestions", withExtension: "zsh")

    /// The `.zshenv` zsh reads from our ZDOTDIR.
    static let bootstrapScript = #"""
    # Tern shell integration bootstrap. Generated by Tern on every launch; do not edit.
    #
    # Tern starts zsh with ZDOTDIR pointing here so this file runs first. Restore
    # the user's ZDOTDIR, load the user's own .zshenv, then load the integration.
    if [[ -n "${TERN_ORIG_ZDOTDIR+set}" ]]; then
      'builtin' 'export' ZDOTDIR="$TERN_ORIG_ZDOTDIR"
      'builtin' 'unset' TERN_ORIG_ZDOTDIR
    else
      'builtin' 'unset' ZDOTDIR
    fi
    {
      # An unset ZDOTDIR means $HOME, as in zsh itself.
      'builtin' 'typeset' _tern_file="${ZDOTDIR-$HOME}/.zshenv"
      [[ ! -r "$_tern_file" ]] || 'builtin' 'source' '--' "$_tern_file"
    } always {
      if [[ -o interactive && -r "${TERN_SHELL_INTEGRATION-}" ]]; then
        'builtin' 'source' '--' "$TERN_SHELL_INTEGRATION"
      fi
      'builtin' 'unset' _tern_file TERN_SHELL_INTEGRATION
    }

    """#

    /// Hooks that report the prompt/command lifecycle and working directory,
    /// and optionally turn on command suggestions.
    static let integrationScript = #"""
    # Tern shell integration for zsh. Generated by Tern on every launch; do not edit.
    #
    # Reports the shell lifecycle to the terminal with escape sequences:
    #   OSC 133;A                     prompt started
    #   OSC 133;C;cmdline_url=<cmd>   command started (percent-encoded command line)
    #   OSC 133;D;<status>            command finished
    #   OSC 7;file://<host><cwd>      current working directory
    # Every OSC 133 carries aid=<token> so the terminal can tell this shell's
    # marks from ones printed by nested shells, ssh sessions or `cat`.
    # Hooks are added with add-zsh-hook and PS1 is left alone, so prompt themes
    # keep working; zsh gives every precmd hook the same $?.
    # With TERN_AUTOSUGGEST set, it also turns on command suggestions.

    [[ -o interactive ]] || 'builtin' 'return' 0
    (( ${+_tern_aid} )) && 'builtin' 'return' 0

    'builtin' 'typeset' -g _tern_aid="${TERN_SHELL_INTEGRATION_AID-}"
    'builtin' 'unset' TERN_SHELL_INTEGRATION_AID
    'builtin' 'typeset' -gi _tern_command_running=0

    # Percent-encodes $1 byte by byte into REPLY, keeping RFC 3986 unreserved
    # characters and '/'.
    _tern_urlencode() {
      'builtin' 'emulate' -L zsh -o extendedglob
      'builtin' 'local' LC_ALL=C
      REPLY=${1//(#m)[^A-Za-z0-9\/._~-]/%${(l:2::0:)$(( [##16] #MATCH ))}}
    }

    _tern_precmd() {
      'builtin' 'local' -i last_status=$?
      if (( _tern_command_running )); then
        _tern_command_running=0
        'builtin' 'printf' '\e]133;D;%d;aid=%s\a' "$last_status" "$_tern_aid"
      fi
      'builtin' 'local' REPLY
      _tern_urlencode "$PWD"
      'builtin' 'printf' '\e]7;file://%s%s\a' "$HOST" "$REPLY"
      'builtin' 'printf' '\e]133;A;aid=%s\a' "$_tern_aid"
    }

    _tern_preexec() {
      'builtin' 'local' REPLY
      _tern_urlencode "$1"
      'builtin' 'printf' '\e]133;C;aid=%s;cmdline_url=%s\a' "$_tern_aid" "$REPLY"
      _tern_command_running=1
    }

    'builtin' 'autoload' -Uz add-zsh-hook
    add-zsh-hook precmd _tern_precmd
    add-zsh-hook preexec _tern_preexec

    # Command suggestions: zsh-autosuggestions shows the rest of a matching
    # history entry in gray. Set up at the first prompt, after the user's
    # .zshrc, so a copy the user loads themselves wins and a Tab key the user
    # has rebound is left alone.
    'builtin' 'typeset' -g _tern_autosuggest="${TERN_AUTOSUGGEST-}"
    'builtin' 'unset' TERN_AUTOSUGGEST

    _tern_setup_autosuggest() {
      add-zsh-hook -d precmd _tern_setup_autosuggest
      if (( ! ${+functions[_zsh_autosuggest_start]} )); then
        [[ -r "$_tern_autosuggest" ]] || 'builtin' 'return' 0
        'builtin' 'source' '--' "$_tern_autosuggest" || 'builtin' 'return' 0
        _zsh_autosuggest_start
      fi
      if [[ "$('builtin' 'bindkey' '^I')" == '"^I" expand-or-complete' ]]; then
        'builtin' 'zle' -N _tern_accept_or_complete
        # Left unwrapped: the plugin's wrapper clears the suggestion before
        # calling the widget.
        ZSH_AUTOSUGGEST_IGNORE_WIDGETS+=(_tern_accept_or_complete)
        'builtin' 'bindkey' '^I' _tern_accept_or_complete
      fi
    }

    # Tab accepts the suggestion when one is shown and completes otherwise.
    _tern_accept_or_complete() {
      if [[ -n "$POSTDISPLAY" ]]; then
        'builtin' 'zle' autosuggest-accept
      else
        'builtin' 'zle' expand-or-complete
      fi
    }

    [[ -z "$_tern_autosuggest" ]] || add-zsh-hook precmd _tern_setup_autosuggest

    """#
}
